CREATE TABLE IF NOT EXISTS organizations (
  id CHAR(36) NOT NULL PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  type ENUM('SUPPLIER','BUYER') NOT NULL DEFAULT 'BUYER',
  facility_type VARCHAR(80) NULL,
  gstin VARCHAR(15) NULL,
  email VARCHAR(190) NULL,
  phone VARCHAR(25) NULL,
  address VARCHAR(300) NULL,
  city VARCHAR(80) NULL,
  state VARCHAR(80) NULL,
  pincode VARCHAR(10) NULL,
  latitude DECIMAL(10,7) NULL,
  longitude DECIMAL(10,7) NULL,
  preferences JSON NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  KEY idx_organizations_type (type),
  KEY idx_organizations_city (city)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) NOT NULL PRIMARY KEY,
  organization_id CHAR(36) NULL,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  password_hash VARCHAR(100) NULL,
  role ENUM('ADMIN','SUPPLIER','BUYER','FULFILLMENT') NOT NULL DEFAULT 'BUYER',
  phone VARCHAR(25) NULL,
  gstin VARCHAR(15) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  invitation_token VARCHAR(80) NULL,
  invitation_expires_at DATETIME NULL,
  last_login_at DATETIME NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY uq_users_email (email),
  UNIQUE KEY uq_users_invitation_token (invitation_token),
  KEY idx_users_role (role),
  KEY idx_users_organization_id (organization_id),
  CONSTRAINT fk_users_organization FOREIGN KEY (organization_id) REFERENCES organizations(id) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


CREATE TABLE IF NOT EXISTS orders (
  id CHAR(36) NOT NULL PRIMARY KEY,
  order_number VARCHAR(30) NOT NULL,
  user_id CHAR(36) NOT NULL,
  shipping_address_id CHAR(36) NULL,
  assigned_to_id CHAR(36) NULL,
  buyer_name VARCHAR(120) NULL,
  buyer_org VARCHAR(160) NULL,
  billing_gstin VARCHAR(15) NULL,
  shipping_address_json JSON NULL,
  status ENUM('PENDING','CONFIRMED','PROCESSING','PICKING','PACKED','READY_FOR_DISPATCH','OUT_FOR_DELIVERY','DELIVERED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  payment_status ENUM('PENDING','PAID','FAILED','REFUNDED') NOT NULL DEFAULT 'PENDING',
  payment_method ENUM('UPI','CARD','BANK_TRANSFER','COD','RAZORPAY') NOT NULL DEFAULT 'COD',
  subtotal DECIMAL(12,2) NOT NULL DEFAULT 0,
  tax DECIMAL(12,2) NOT NULL DEFAULT 0,
  shipping_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
  total DECIMAL(12,2) NOT NULL DEFAULT 0,
  expected_delivery VARCHAR(80) NULL,
  notes TEXT NULL,
  placed_at DATETIME NOT NULL,
  delivered_at DATETIME NULL,
  cancelled_at DATETIME NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY uq_orders_order_number (order_number),
  KEY idx_orders_user_created (user_id,created_at),
  KEY idx_orders_status (status),
  KEY idx_orders_assigned_to (assigned_to_id),
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_orders_shipping_address FOREIGN KEY (shipping_address_id) REFERENCES addresses(id) ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_orders_assignee FOREIGN KEY (assigned_to_id) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

